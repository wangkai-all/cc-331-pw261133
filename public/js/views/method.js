/**
 * Method notes.
 *
 * A reading page, not a control surface. It states the modelling choices and,
 * more importantly, what the replay refuses to claim.
 */

import { h } from '../util.js';
import { pageHead, panel } from './common.js';

export function renderMethod() {
  return h(
    'div',
    {},
    pageHead({
      title: '方法说明',
      subtitle: '这个沙盒如何生成数据、如何估计，以及它刻意不回答哪些问题。',
    }),
    h(
      'div',
      { class: 'grid cols-2', style: { alignItems: 'start' } },
      panel({
        title: '1 · 世界与时钟',
        body: prose([
          '一个虚构 SKU（Aurora 降噪耳机），四个渠道共用**一个**库存池。每个模拟日拆成六个两小时时段，时钟每前进一次推进一个时段。',
          '每个时段、每个渠道：先由需求模型给出**潜在**购买意图，再按固定渠道顺序尝试为每一单锁定 1 件库存。库存不足时该渠道的观测在这一时段被截断，靠后的渠道这一时段完全拿不到货。',
          '潜在需求从不写入事件日志。日志里只有曝光数、点击、成交数、库存流水、订单状态和缺货标记——和真实系统能观测到的范围一致。',
        ]),
      }),
      panel({
        title: '2 · 库存的两阶段预留',
        body: prose([
          '下单时创建**软预留**：可售 −1，预留中 +1，并带过期时间。支付成功后转为**已承诺**；取消或过期则释放回可售；退货在若干天后把已承诺的单位退回可售。',
          '不变量：可售 + 预留中 + 已承诺 = 期初 + 补货。事件流里每条预留/释放/占用/退回都带订单号，所以每个单位都能追到去向。',
          '这也是为什么不能把“销量低”直接读成“需求低”：某个渠道可能只是排序靠后，在它之前库存已经被别的渠道买空了。',
        ]),
      }),
      panel({
        title: '3 · 删失与需求假设',
        body: prose([
          '「删失」指我们只看到成交数的下界：库存耗尽时，我们不知道有多少购买意图没有实现。日志里的 `orders` 在那种时段是一个**下界**，不是需求测量。',
          '估计时对三种处理方式给出对照：**截断似然**（缺货时段贡献 P(成交 ≥ 观测值)）、**剔除**（丢掉这些时段）、以及**当作完整观测**（把零成交读成零需求，错误做法）。第三种会系统性地把缺货惩罚成“价格无效”，界面会明确标红。',
          '开始时段就无货的观测不含任何需求信息，即使使用截断似然也会被丢弃。',
        ]),
      }),
      panel({
        title: '4 · 按渠道估计 vs 联合估计',
        body: prose([
          '**按渠道独立**：每个渠道各自的截距和价格斜率。简单，但它把渠道当成孤岛：忽略共享库存的顺序竞争，也忽略跨渠道价格。',
          '**联合（共享库存）**：渠道固定效应 + 每个渠道自己的价格斜率 + 一个共享交叉价格项 γ，全部渠道一起最大化截断似然。截断阈值按渠道处理顺序确定。',
          'γ 只有在数据能识别时才保留。现实中各渠道往往同向调价，γ 会与自身价格共线，这时模型退回 γ=0 的加性形式，并在界面上说明“该项不可识别”，而不是给一个巨大的标准误把每个区间都撑爆。',
        ]),
      }),
      panel({
        title: '5 · 什么时候说“不可识别”',
        body: prose([
          '价格从未变过（少于两个价位或变动幅度不足 2%）、未截断样本过少、价格与时间高度共线——这些情况下斜率无法从数据中分离出来。界面会把该渠道标为**不可识别**，斜率固定为先验值并明确说明，而不是给出一个看似精确实则编造的数字。',
          '回测同理：每个窗口只用当日收市为止的事件拟合，预测次日转化率；被截断的次日只记录、不打分。否则“缺货导致成交量低”会被误记为预测失败。',
        ]),
      }),
      panel({
        title: '6 · 方案生命周期与资源干扰',
        body: prose([
          '草稿 → 确认 → 上线 → 被取代。确认会冻结价格、规则版本和库存预留；规则版本一旦变化，已确认方案立即失效，需要重新核对。上线新方案时旧方案被标记为“已被取代”，不能再被重新启用。',
          '多个方案的预留从**同一个**共享池里扣：预留合计不能超过可承诺库存，确认后还要给实时交易留缓冲。并列试算只是菜单式比较——每个试算在克隆引擎上跑，共享同一库存假设，所以结果不能相加，也不能同时上线。',
        ]),
      }),
      panel({
        title: '7 · 边界',
        body: h(
          'div',
          { class: 'callout warn' },
          '全部数据为虚构回放，不连接任何真实销售、库存或支付系统。试算结果是“若现在改价”的情景投影，由与回放相同的需求模型生成；它不是实验结果，也不是无偏预测。需求参数是设定的，不是从数据中估出来的——这个实验室演示的是**方法上的陷阱**，而不是给出某个真实商品的价格建议。',
        ),
      }),
    ),
  );
}

function prose(paragraphs) {
  return h(
    'div',
    { class: 'small', style: { display: 'flex', flexDirection: 'column', gap: '8px', color: 'var(--text-2)' } },
    paragraphs.map((text) => h('p', { style: { margin: 0, lineHeight: '1.7' }, html: inline(text) })),
  );
}

/** Minimal **bold** → <b> conversion for the prose above. */
function inline(text) {
  return text.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
}
