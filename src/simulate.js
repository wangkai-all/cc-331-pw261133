/**
 * Dry-run simulator for candidate plans.
 *
 * A simulation never touches the live session. It builds a throw-away engine
 * from the current snapshot, applies the candidate plan (or, for an unconfirmed
 * draft, injects the price vector directly), and steps forward. The result is
 * labelled a *scenario projection*: it mixes a "what if" price with the world's
 * demand model, so it is not an experiment result and not an unbiased forecast
 * either.
 *
 * When several plans are compared the runner reports both their projections and
 * whether they compete for the same shared stock — the resource-interference
 * warning that a parallel test must surface.
 */

import { ReplayEngine, MAX_TICKS } from './engine.js';
import {
  PLAN_STATUS,
  priceDiff,
  rulesSnapshotFor,
} from './plans.js';
import { CHANNELS, DAY_HOURS, SKU, findChannel, fmt } from './world.js';
import { buildRulebook } from './rules.js';

export const SIM_HORIZON_DEFAULT = 3 * DAY_HOURS;

function cloneEngineFor(session, { overridePrices = null, claimUnits = 0 } = {}) {
  const snapshot = JSON.parse(JSON.stringify(session.engine.toJSON()));
  const sandbox = ReplayEngine.fromJSON(snapshot);
  sandbox.setRuleEpochForSandbox?.(session.ruleEpoch);
  sandbox.ruleEpoch = session.ruleEpoch;
  sandbox.rulebook = buildRulebook(session.ruleEpoch);
  // Reserve the claimed units in the sandbox so parallel projections do not
  // each assume the whole pool is available.
  if (claimUnits > 0) {
    const reserve = Math.min(claimUnits, sandbox.inventory.units.available);
    sandbox.inventory.units.available -= reserve;
    sandbox.inventory.units.held += reserve;
  }
  if (overridePrices) {
    sandbox.sandboxPrices = { ...overridePrices };
  }
  return sandbox;
}

/**
 * Step a sandbox while pretending a price vector is in force. This bypasses the
 * plan workflow on purpose (the sandbox log is discarded), but the observations
 * it produces are still generated by the same demand model.
 */
function stepSandbox(sandbox, ticks) {
  const originalCurrent = sandbox.currentPrices;
  const forced = sandbox.sandboxPrices;
  const forcedPlan = forced
    ? {
        ...sandbox.addPlan({
            name: 'sandbox',
            prices: forced,
            note: 'sandbox override',
          }),
        status: PLAN_STATUS.CONFIRMED,
      }
    : null;
  if (forcedPlan) {
    sandbox.plans.push(forcedPlan);
    sandbox.appliedPlanId = forcedPlan.id;
  }
  for (let i = 0; i < ticks && !sandbox.isComplete; i += 1) sandbox.step();
  return { originalCurrent, forced };
}

function summarizeRun(sandbox, { startTick, ticks, baselinePaidByChannel = null }) {
  const observations = sandbox.observations.filter((o) => o.tick > startTick);
  const byChannel = {};
  for (const channel of CHANNELS) {
    const rows = observations.filter((o) => o.channelId === channel.id);
    const impressions = rows.reduce((s, r) => s + r.impressions, 0);
    const orders = rows.reduce((s, r) => s + r.orders, 0);
    const truncatedTicks = rows.filter((r) => r.truncated).length;
    byChannel[channel.id] = {
      impressions,
      orders,
      conversion: impressions ? orders / impressions : null,
      truncatedTicks,
      censoredShare: rows.length ? truncatedTicks / rows.length : 0,
    };
  }
  const orders = [...sandbox.orders.values()].filter((o) => o.createdTick > startTick);
  const paid = orders.filter((o) => o.state === 'paid' || o.state === 'returned');
  const cancelled = orders.filter((o) => o.state === 'cancelled');
  const returned = orders.filter((o) => o.state === 'returned');
  const paidUnitsByChannel = {};
  for (const channel of CHANNELS) {
    paidUnitsByChannel[channel.id] = paid.filter((o) => o.channelId === channel.id).length;
  }
  const pricePaid = {};
  for (const channel of CHANNELS) {
    const paidRows = paid.filter((o) => o.channelId === channel.id);
    pricePaid[channel.id] = paidRows.length
      ? paidRows.reduce((s, o) => s + o.priceCents, 0) / paidRows.length
      : sandbox.currentPrices[channel.id];
  }
  const revenue = paid.reduce((s, o) => s + o.priceCents, 0) - returned.reduce((s, o) => s + o.priceCents, 0);
  let contribution = 0;
  for (const channel of CHANNELS) {
    const rule = sandbox.rulebook[channel.id];
    contribution += paidUnitsByChannel[channel.id] * (pricePaid[channel.id] - SKU.unitCostCents - rule.feeCents);
  }
  return {
    ticks,
    observations: observations.length,
    impressions: observations.reduce((s, r) => s + r.impressions, 0),
    ordersPlaced: orders.length,
    ordersPaid: paid.length,
    ordersCancelled: cancelled.length,
    ordersReturned: returned.length,
    revenueCents: revenue,
    contributionCents: contribution,
    stockoutTicks: sandbox.stockouts.filter((s) => s.tick > startTick).length,
    inventoryEnd: sandbox.inventory.snapshot(),
    paidUnitsByChannel,
    avgPaidPriceCents: pricePaid,
    byChannel,
  };
}

export function runSimulation(session, planId, { horizonTicks = SIM_HORIZON_DEFAULT } = {}) {
  const plan = session.engine.findPlan(planId);
  if (!plan) return { ok: false, error: '未找到方案。' };
  const live = session.engine;
  const remaining = MAX_TICKS - live.tick;
  const ticks = Math.max(1, Math.min(horizonTicks, remaining));
  const startTick = live.tick;

  const claim = live.claims.find((c) => c.planId === plan.id && c.releasedAtTick == null);
  const claimUnits = claim ? claim.units : 0;

  // Baseline: what happens if the current plan stays in force.
  const baselineSandbox = cloneEngineFor(session, { claimUnits });
  stepSandbox(baselineSandbox, ticks);
  const baseline = summarizeRun(baselineSandbox, { startTick, ticks });

  // Candidate: the draft's (or confirmed plan's) prices are forced in the sandbox.
  const candidateSandbox = cloneEngineFor(session, { overridePrices: plan.prices, claimUnits });
  stepSandbox(candidateSandbox, ticks);
  const candidate = summarizeRun(candidateSandbox, { startTick, ticks });

  const deltaOrders = candidate.ordersPaid - baseline.ordersPaid;
  const deltaContribution = candidate.contributionCents - baseline.contributionCents;
  const deltaStockoutTicks = candidate.stockoutTicks - baseline.stockoutTicks;

  const warnings = [];
  if (candidate.byChannel) {
    for (const channel of CHANNELS) {
      if (candidate.byChannel[channel.id].censoredShare > 0.35) {
        warnings.push({
          level: 'warn',
          code: 'sim_truncation',
          message: `${channel.name} 在试算窗口内约 ${(candidate.byChannel[channel.id].censoredShare * 100).toFixed(
            0,
          )}% 时段被库存截断，该渠道的试算订单不能当作需求。`,
        });
      }
    }
  }
  if (deltaStockoutTicks > 6) {
    warnings.push({
      level: 'warn',
      code: 'sim_resource_interference',
      message: '低价方案会把共享库存更早耗尽，后续渠道（按处理顺序靠后的）将先失去成交机会。',
    });
  }
  if (live.inventory.units.available - live.claimedUnits() < claimUnits) {
    warnings.push({
      level: 'bad',
      code: 'sim_claim_conflict',
      message: '当前可用库存已不足以覆盖本方案的预留，试算结果建立在不可兑现的库存上。',
    });
  }

  const baselinePrices = live.currentPrices;
  return {
    ok: true,
    planId: plan.id,
    planName: plan.name,
    status: plan.status,
    startTick,
    horizonTicks: ticks,
    kind: 'scenario_projection',
    disclaimer:
      '这是“若今天起改用该价格”的情景试算，不是实验结果。它用同一套需求模型推演，且与真实回放共享同一库存池，不能替代正式实验。',
    prices: {
      baseline: baselinePrices,
      candidate: { ...plan.prices },
      diff: priceDiff(baselinePrices, plan.prices),
    },
    baseline,
    candidate,
    delta: {
      ordersPaid: deltaOrders,
      contributionCents: deltaContribution,
      stockoutTicks: deltaStockoutTicks,
      orderPct: baseline.ordersPaid ? (deltaOrders / baseline.ordersPaid) * 100 : null,
    },
    claims: {
      units: claimUnits,
      claimedByOthers: live.claimedUnits({ excludePlanId: plan.id }),
      free: Math.max(0, live.inventory.units.available - live.claimedUnits()),
    },
    warnings,
  };
}

/**
 * Compare several plans side by side. Plans compete for the same stock, so the
 * comparison is a menu, not a portfolio: using more than one at the same time
 * would double-count the pool.
 */
export function runComparison(session, planIds, { horizonTicks = SIM_HORIZON_DEFAULT } = {}) {
  const runs = planIds
    .map((id) => runSimulation(session, id, { horizonTicks }))
    .filter((r) => r.ok);
  const claimSum = runs.reduce((s, r) => s + (r.claims?.units ?? 0), 0);
  const free = session.engine.inventory.units.available - session.engine.claimedUnits();
  const duplicateSets = [];
  for (let i = 0; i < runs.length; i += 1) {
    for (let j = i + 1; j < runs.length; j += 1) {
      const same = CHANNELS.every((c) => runs[i].prices.candidate[c.id] === runs[j].prices.candidate[c.id]);
      if (same) duplicateSets.push([runs[i].planId, runs[j].planId]);
    }
  }
  return {
    ok: true,
    kind: 'scenario_projection',
    horizonTicks,
    runs,
    resource: {
      freeUnits: Math.max(0, free),
      claimSum,
      overCommitted: claimSum > free,
      note:
        claimSum > free
          ? '多个方案的预留合计已超过可承诺库存：它们不能同时上线，试算之间也会互相抢库存。'
          : '预留合计仍在可承诺库存内，但试算各自的库存假设并未串行叠加，正式实验仍需一次只跑一个价格。',
    },
    duplicates: duplicateSets,
    note: '同一库存池只能同时执行一个价格方案；并列比较是菜单选择，不是可以同时投放的组合。',
  };
}

